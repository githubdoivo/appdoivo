export function getLang() {
  const stored = localStorage.getItem(LANG_KEY);
  return stored === 'en' || stored === 'pt' ? stored : 'pt';
}

export function setLang(lang) {
  localStorage.setItem(LANG_KEY, lang);
  // Best-effort: remembers the choice server-side so push notifications can
  // later be sent in it. Silently ignored when logged out or offline.
  if (getToken()) {
    api('/me/lang', { method: 'POST', body: { lang } }).catch(() => {});
  }
}

/** Traduz uma chave, substituindo {params}. */
export function t(key, params = {}) {
  const lang = getLang();
  let str = translations[lang]?.[key] ?? translations.pt[key] ?? key;
  for (const [k, v] of Object.entries(params)) {
    str = str.replaceAll(`{${k}}`, v);
  }
  return str;
}

/** Aplica traducoes a elementos com data-i18n / data-i18n-ph. */
export function applyI18n(root = document) {
  // One sentence per line, same rule as dialogs (modal.js) and the tour:
  // help text left to wrap freely puts the end of one sentence and the start
  // of the next on the same line.
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const sentences = t(el.dataset.i18n).split(/(?<=[.!?])\s+/);
    el.textContent = sentences.join('\n');
    if (sentences.length > 1) el.style.whiteSpace = 'pre-line';
  });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  // For controls whose label is not text they can hold - an icon button's
  // name lives in aria-label and title, and writing it into textContent
  // would paint the word over the icon.
  root.querySelectorAll('[data-i18n-label]').forEach((el) => {
    const label = t(el.dataset.i18nLabel);
    el.setAttribute('aria-label', label);
    el.setAttribute('title', label);
  });
  document.documentElement.lang = getLang();
}
